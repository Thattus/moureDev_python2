
def sum(numberOne, numberTwo, numberThree=0):
    """
    This function takes three numbers as arguments and prints their sum. The third number is optional and defaults to 0 if not provided.
    """
    print(numberOne + numberTwo + numberThree)

def printValue(value):
    """
        This function takes a value as an argument and prints it.
    """
    print(f"Value: {value}")